// Writes src/assets.ts: size and SHA-256 of every engine file, from the installed npm packages
// (the same versions the CDNs serve). Run after changing an engine version: npm run pin.
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { join } from "node:path";
import { ENGINES } from "../src/registry.ts";
import { findPackageDir } from "../src/node.ts";

const pins: Record<string, { size: number; sha256: string }> = {};
for (const e of ENGINES) {
  const dir = findPackageDir(e.package.name, e.package.version);
  if (!dir) throw new Error(`${e.package.name}@${e.package.version} is not installed: npm install`);
  for (const a of e.assets) {
    const file = join(dir, a);
    if (!existsSync(file)) throw new Error(`missing ${file}`);
    const data = readFileSync(file);
    pins[`${e.package.name}@${e.package.version}/${a}`] = { size: data.length, sha256: createHash("sha256").update(data).digest("hex") };
  }
}
const body = Object.entries(pins).map(([k, v]) => `  ${JSON.stringify(k)}: { size: ${v.size}, sha256: "${v.sha256}" },`).join("\n");
writeFileSync(new URL("../src/assets.ts", import.meta.url), `// Generated by scripts/pin.ts: size and SHA-256 of each engine file. Do not edit.\nexport const PINS: Record<string, { size: number; sha256: string }> = {\n${body}\n};\n`);
console.log(`${Object.keys(pins).length} files pinned`);
